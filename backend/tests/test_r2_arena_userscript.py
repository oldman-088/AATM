ADMIN = {"Authorization": f"Bearer {BRIDGE_TOKEN}"}


class Harness:
    def __init__(self, factory, bridge, headers) -> None:
        self.factory, self.bridge, self.headers = factory, bridge, headers
        self.client = AsyncClient(transport=ASGITransport(app=app), base_url="http://test", timeout=120)

    async def setup_profile(self, agent_id: str) -> tuple[str, str]:
        async with self.factory() as db:
            profile_id = (await db.get(Agent, agent_id)).browser_profile_id
        r = await self.client.put(f"/api/v1/arena/agents/{agent_id}/mode", json={"mode": "agent"}, headers=self.headers)
        assert r.status_code == 200, r.text
        r = await self.client.post(f"/api/v1/arena/profiles/{profile_id}/userscript", headers=self.headers)
        assert r.status_code == 200 and r.json()["bridge_registration"]["ok"], r.text
        return profile_id, r.json()["script"]

    async def cmd(self, profile_id: str, command: str, text: str | None = None) -> httpx.Response:
        body = {"command": command, **({"text": text} if text is not None else {})}
        return await self.client.post(f"/api/v1/arena/profiles/{profile_id}/command", json=body, headers=self.headers)

    async def state(self, profile_id: str) -> dict:
        async with httpx.AsyncClient(base_url=self.bridge.base, headers=ADMIN) as http:
            return (await http.get(f"/v1/connector/profiles/{profile_id}")).json()

    async def wait_state(self, profile_id: str, wanted: str | set[str], timeout: float = 20) -> dict:
        wanted = {wanted} if isinstance(wanted, str) else wanted
        deadline = time.monotonic() + timeout
        last: dict = {}
        while time.monotonic() < deadline:
            last = await self.state(profile_id)
            if last.get("agent_state") in wanted and last.get("connected"):
                return last
            await asyncio.sleep(0.1)
        raise AssertionError(f"{profile_id} never reached {wanted}: {last.get('agent_state')} {last.get('recent_events')}")


