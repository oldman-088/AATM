async def test_new_session_url_navigation_and_contenteditable_composer(harness, arena_settings, monkeypatch):
    from playwright.async_api import async_playwright

    url = f"{harness.bridge.base}/mock-arena/agent/?composer=contenteditable&gen_ms=300&fresh=1"
    monkeypatch.setattr(arena_settings, "ARENA_AGENT_NEW_SESSION_URL", url)
