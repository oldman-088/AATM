    async with async_playwright() as pw:
        browser = await _browser(pw)
        try:
            page = await _open(browser, script, f"{harness.bridge.base}/mock-arena/agent/?composer=contenteditable&gen_ms=300")
            await harness.wait_state(pid, "ready")
            r = await harness.cmd(pid, "submit", "Edit a contenteditable composer")
            assert r.status_code == 200 and r.json()["result"]["sent"], r.text
            await harness.wait_state(pid, "idle", timeout=20)
            before = (await harness.state(pid))["connections_total"]

            r = await harness.cmd(pid, "new_session")
            assert r.status_code == 200 and r.json()["result"]["navigating"] is True
            await page.wait_for_url(url, timeout=10_000)
            ready = await harness.wait_state(pid, "ready")
            assert ready["connections_total"] == before + 1  # the reloaded page reconnected by itself
            assert await page.locator("[data-message-author-role]").count() == 0
        finally:
            await browser.close()


