@needs_chromium
async def test_userscript_runs_every_command_on_the_mock_agent_page(harness, caplog):
    from playwright.async_api import async_playwright

    caplog.set_level(logging.DEBUG)
    pid, script = await harness.setup_profile("worker-1")
    base = f"{harness.bridge.base}/mock-arena/agent/"
    async with async_playwright() as pw:
        browser = await _browser(pw)
        try:
            page = await _open(browser, script, f"{base}?gen_ms=700&kw_rounds=1")
            await harness.wait_state(pid, "ready")

            # selector_test is read-only: it finds everything and sends nothing.
            r = await harness.cmd(pid, "selector_test")
            assert r.status_code == 200, r.text
            rep = r.json()["result"]
            assert rep["composer"]["found"] and rep["composer"]["tag"] == "textarea"
            assert rep["new_session"]["found"] and rep["stop"]["found"] is False
            assert rep["keep_working"]["found"] is False and rep["human_check"]["found"] is False
            assert rep["state"] == "ready" and rep["ok"] is True
            assert (await page.evaluate("window.__mockArena"))["submits"] == 0
            assert (await harness.state(pid))["selector_report"]["composer"]["found"] is True

            # submit -> generating (Stop visible) -> keep_working_visible.
            prompt = "[AATM-t1] Implement feature.py with tests."
            r = await harness.cmd(pid, "submit", prompt)
            assert r.status_code == 200 and r.json()["result"]["sent"] is True, r.text
            assert r.json()["result"]["how"] in {"send_button", "form_submit", "enter", "enter_retry"}
            kw_state = await harness.wait_state(pid, "keep_working_visible")
            kinds = [e["kind"] for e in kw_state["recent_events"]]
            assert kinds.index("command:submit") < kinds.index("state:generating") < kinds.index("state:keep_working_visible")
            assert await page.locator("[data-message-author-role='user']").inner_text() == prompt

            # keep_working continues the task; idle only after five quiet seconds.
            r = await harness.cmd(pid, "keep_working")
            assert r.status_code == 200 and r.json()["result"]["clicked"] is True
            clicked_at = time.monotonic()
            idle = await harness.wait_state(pid, "idle", timeout=20)
            # gen_ms=700 + the five-second idle double-check
            assert time.monotonic() - clicked_at >= 5.0 and idle["keep_working_clicks"] == 1
            kinds = [e["kind"] for e in idle["recent_events"]]
            assert kinds[kinds.index("command:keep_working"):].count("state:generating") == 1
            again = await harness.cmd(pid, "keep_working")  # nothing to click -> reported, not faked
            assert again.json()["result"]["clicked"] is False

            r = await harness.cmd(pid, "read_last_reply")
            assert r.status_code == 200
            reply = r.json()["result"]
            assert reply["found"] and "Implementation summary: mock work done." in reply["text"]
            stats = await page.evaluate("window.__mockArena")
            assert stats["submits"] == 1 and stats["kw_clicks"] == 1

            # new_session via the page's New button (no URL configured).
            r = await harness.cmd(pid, "new_session")
            assert r.status_code == 200 and r.json()["result"]["ready"] is True, r.text
            await harness.wait_state(pid, "ready")
            assert await page.locator("[data-message-author-role]").count() == 0
            assert (await page.evaluate("window.__mockArena"))["new_sessions"] == 1

            # A follow-up message in the same session works like a submit.
            r = await harness.cmd(pid, "submit", "Follow-up: also add a docstring.")
            assert r.status_code == 200
            await harness.wait_state(pid, "keep_working_visible", timeout=20)  # kw_rounds=1 per message
            assert (await page.evaluate("window.__mockArena"))["submits"] == 2

            # Planted page secrets never reach logs, bridge events or the database.
            dump = json.dumps(await harness.state(pid))
            async with harness.factory() as db:
                dump += json.dumps([list(row) for row in (await db.execute(text("SELECT * FROM audit_logs"))).all()], default=str)
            for secret in PLANTED:
                assert secret not in caplog.text and secret not in dump
            assert prompt not in caplog.text  # prompts are never logged
        finally:
            await browser.close()


