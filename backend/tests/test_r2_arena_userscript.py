@needs_chromium
async def test_human_check_login_wall_and_offline_pages_are_detected(harness):
    from playwright.async_api import async_playwright

    base = f"{harness.bridge.base}/mock-arena/agent/"
    async with async_playwright() as pw:
        browser = await _browser(pw)
        try:
            # Human check on load -> needs_human; mutating commands refused, selector_test still reports.
            pid, script = await harness.setup_profile("worker-1")
            page = await _open(browser, script, f"{base}?variant=human_check")
            stopped = await harness.wait_state(pid, "needs_human")
            assert stopped["status"] == "needs_human" and "human check" in stopped["needs_human_reason"]
            r = await harness.cmd(pid, "submit", "should not be sent")
            assert r.status_code == 409 and r.json()["detail"]["code"] == "needs_human"
            probe = await harness.cmd(pid, "selector_test")
            assert probe.status_code == 200 and probe.json()["result"]["human_check"]["found"] is True
            assert (await page.evaluate("window.__mockArena"))["submits"] == 0
            # The human resolves it in the browser, then presses Resume in AATM.
            await page.evaluate("document.querySelector('[data-aatm-human-check]').remove()")
            resumed = await harness.client.post(f"/api/v1/arena/profiles/{pid}/resume", headers=harness.headers)
            assert resumed.status_code == 200 and resumed.json()["connector_status"] == "ready"
            await harness.wait_state(pid, "ready")
            assert (await harness.cmd(pid, "submit", "after the human")).status_code == 200

            # A human check that appears after sending stops the session too.
            pid2, script2 = await harness.setup_profile("worker-2")
            await _open(browser, script2, f"{base}?variant=human_check_after_send")
            await harness.wait_state(pid2, "ready")
            trig = await harness.cmd(pid2, "submit", "trigger")
            assert trig.status_code == 200 and trig.json()["result"]["sent"] is True, trig.text  # it really was sent
            await harness.wait_state(pid2, "needs_human")
            again = await harness.cmd(pid2, "submit", "trigger again")
            assert again.status_code == 409

            # Login wall -> needs_human (the human signs in; AATM never handles credentials).
            pid3, script3 = await harness.setup_profile("worker-3")
            await _open(browser, script3, f"{base}?variant=login")
            login = await harness.wait_state(pid3, "needs_human")
            assert "sign in to continue" in login["needs_human_reason"]

            # Disconnected session -> offline; it recovers to ready and monitoring continues.
            pid4, script4 = await harness.setup_profile("worker-4")
            await _open(browser, script4, f"{base}?variant=recover&recover_ms=2500")
            offline = await harness.wait_state(pid4, "offline")
            assert offline["connected"] is True and offline["status"] == "ready"
            await harness.wait_state(pid4, "ready", timeout=15)
            events = [e["kind"] for e in (await harness.state(pid4))["recent_events"]]
            assert events.index("state:offline") < len(events) - 1 - events[::-1].index("state:ready")
        finally:
            await browser.close()


@needs_chromium
async def test_session_recovery_after_reload_and_many_profiles_stay_independent(harness):
    from playwright.async_api import async_playwright

    base = f"{harness.bridge.base}/mock-arena/agent/?gen_ms=400"
    async with async_playwright() as pw:
        browser = await _browser(pw)
        try:
            profiles = []
            for agent_id in ("worker-1", "worker-2", "worker-3", "worker-4"):
                pid, script = await harness.setup_profile(agent_id)
                profiles.append((pid, await _open(browser, script, base)))
            for pid, _ in profiles:
                await harness.wait_state(pid, "ready")
            results = await asyncio.gather(*(harness.cmd(pid, "submit", f"task for {pid}") for pid, _ in profiles))
            assert all(r.status_code == 200 for r in results), [r.text for r in results]
            for pid, page in profiles:
                await harness.wait_state(pid, "idle", timeout=20)
                assert await page.locator("[data-message-author-role='user']").inner_text() == f"task for {pid}"

            # The browser tab reloads (crash, update, manual refresh): the script reconnects and
            # monitoring resumes without touching the other profiles.
            pid, page = profiles[0]
            await page.reload()
            recovered = await harness.wait_state(pid, "ready")
            assert recovered["connections_total"] == 2
            assert {(await harness.state(p))["agent_state"] for p, _ in profiles[1:]} == {"idle"}
        finally:
            await browser.close()


