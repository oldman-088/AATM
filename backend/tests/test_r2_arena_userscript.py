"""R2 — the generated Arena Agent userscript against the mock Arena Agent page (real Chromium).

The userscript is generated by the backend, added to each page by the *test* (standing in for the
human installing it in Tampermonkey) and driven only through the bridge:

==================  ==========================================================
new_session         clicks New (or navigates to ARENA_AGENT_NEW_SESSION_URL), reports ready
submit              inserts the prompt into a React-style controlled composer and sends it
keep_working        continues the task when Keep working is shown
read_last_reply     returns the latest agent reply (redacted by the backend)
selector_test       reports every element without typing, clicking or sending
human check         reports needs_human; commands stop until a human resumes
offline             a disconnected-session page reports offline; recovery restores monitoring
==================  ==========================================================
"""

