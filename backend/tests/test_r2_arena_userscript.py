async def test_each_profile_gets_its_own_compliant_attributed_userscript(harness, arena_settings, monkeypatch):
    monkeypatch.setenv("GITHUB_TOKEN", "ghp_PLANTEDGITHUBTOKEN0123456789abcdef")
    p1, s1 = await harness.setup_profile("worker-1")
    p2, s2 = await harness.setup_profile("worker-2")
    assert p1 != p2
    t1 = json.loads(s1.split("var CFG = ")[1].split(";\n")[0])
    t2 = json.loads(s2.split("var CFG = ")[1].split(";\n")[0])
    assert t1["profileId"] == p1 and t2["profileId"] == p2 and t1["token"] != t2["token"]
    assert set(t1) == {"profileId", "token", "bridge", "version"}  # nothing else is embedded
    for script in (s1, s2):
        header = script.split("==/UserScript==")[0]
        assert f"// @match        {harness.bridge.base}/mock-arena/*" in header
        assert "// @grant        none" in header and "@noframes" in header
        assert "arena-auto-continue by Anurag Kumar Nishad, MIT" in header
        assert "Copyright (c) 2026 Anurag Kumar Nishad" in script and "THIRD_PARTY_NOTICES.md" in script
        assert BRIDGE_TOKEN not in script and "ghp_PLANTED" not in script and "SECRET_KEY" not in script
        assert validate_userscript_policy(script, match_patterns()) == (True, "approved")
        lowered = script.lower()
        for forbidden in ("cookie", "localstorage", "sessionstorage", "gm_xmlhttprequest", "unsafewindow", "eval(", "captcha", "fetch("):
            assert forbidden not in lowered, forbidden
        for command in ("new_session", "submit", "keep_working", "read_last_reply", "selector_test"):
            assert command in script
    # Real Arena origins from ARENA_ALLOWED_ORIGINS are added next to the mock page.
    monkeypatch.setattr(arena_settings, "ARENA_CONNECTOR_ENABLED", True)
    monkeypatch.setattr(arena_settings, "ARENA_ALLOWED_ORIGINS", "https://arena.ai,https://beta.arena.ai")
    async with harness.factory() as db:
        profile = await db.get(BrowserProfile, p1)
    real = build_userscript(profile, None, "tok")
    for pattern in (f"{harness.bridge.base}/mock-arena/*", "https://arena.ai/*", "https://beta.arena.ai/*"):
        assert f"// @match        {pattern}" in real
    assert validate_userscript_policy(real, match_patterns()) == (True, "approved")


