async def _browser(playwright):
    executable = detect_playwright_capabilities().get("executable_path")
    return await playwright.chromium.launch(headless=True, **({"executable_path": executable} if executable else {}))


async def _open(browser, script: str, url: str):
    context = await browser.new_context()  # one isolated profile per employee
    # Stands in for Tampermonkey: the reviewed script runs on every load of a matching page.
    await context.add_init_script(script)
    page = await context.new_page()
    await page.goto(url)
    return page


